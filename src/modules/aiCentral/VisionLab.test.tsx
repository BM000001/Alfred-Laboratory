import { beforeEach, expect, it, vi } from 'vitest';
import { fireEvent, render, screen } from '@testing-library/react';
import { VisionLab } from './VisionLab';
import { aiTaskRepository, disciplineRepository } from '../../storage/repositories';
import type { AITask } from './contracts';
beforeEach(async () => { vi.restoreAllMocks(); await Promise.all([aiTaskRepository.clear(), disciplineRepository.clear()]); });
it('requires free account confirmation and clears the key before discovering models', async () => {
  let finish: (value: Response) => void = () => {};
  const pending = new Promise<Response>(resolve => { finish = resolve; });
  const network = vi.spyOn(globalThis, 'fetch').mockReturnValueOnce(pending).mockResolvedValueOnce(Response.json({ connections: [] }));
  render(<VisionLab endpoint="https://central.example" token="central-fixture-token" onChange={async () => {}} />);
  fireEvent.click(screen.getByText('Adicionar conexão de API'));
  fireEvent.change(screen.getByLabelText('Nome da conexão'), { target: { value: 'Meu Gemini' } });
  fireEvent.change(screen.getByLabelText('Chave de API'), { target: { value: 'fixture-key-not-real' } });
  const save = screen.getByRole('button', { name: 'Salvar chave e consultar modelos' });
  expect(save).toBeDisabled(); expect(network).not.toHaveBeenCalled();
  fireEvent.click(screen.getByLabelText(/Conferi que esta conta/)); fireEvent.click(save);
  expect(screen.getByLabelText('Chave de API')).toHaveValue('');
  expect(network).toHaveBeenCalledTimes(1);
  const init = network.mock.calls[0][1]!;
  expect(JSON.parse(String(init.body))).toMatchObject({ provider: 'gemini', apiKey: 'fixture-key-not-real', freeTierConfirmed: true });
  finish(Response.json({ connection: { id: 'example' } }, { status: 201 }));
  await screen.findByText(/Chave aceita para consultar/);
  expect(await aiTaskRepository.getAll()).toHaveLength(0);
  expect(network.mock.calls.every(([url]) => String(url).includes('/v1/connections'))).toBe(true);
});
it('restores successful and failed analyses without network or re-execution', async () => {
  const base: AITask = { id: 'good', version: 1, operation: 'studies.analyze', provider: 'gateway', input: { sourceFileId: 'photo', disciplineId: 'biology', text: '', confidence: 0, profile: 'board', includeImage: true, comparisonId: 'pair', connection: { id: 'c1', provider: 'gemini', label: 'G', model: 'fixture-vision', revision: 'r1', endpoint: 'https://central.example' } }, status: 'completed', attempts: 1, createdAt: new Date().toISOString(), updatedAt: new Date().toISOString(), result: { analysis: { text: 'Mitose: divisão celular.', uncertainties: ['Borda ilegível.'], definitions: [], formulas: [], summary: '', requiresReview: true } } };
  await aiTaskRepository.save(base);
  await aiTaskRepository.save({ ...base, id: 'failed', status: 'failed', result: undefined, error: { code: 'HTTP_429', message: 'Cota atingida.' }, input: { ...base.input, connection: { ...base.input.connection!, id: 'c2', provider: 'groq' } } });
  const network = vi.spyOn(globalThis, 'fetch');
  const view = render(<VisionLab endpoint="https://central.example" token="" onChange={async () => {}} />);
  expect(await screen.findByText('Mitose: divisão celular.')).toBeInTheDocument();
  expect(screen.getByText('Cota atingida.')).toBeInTheDocument();
  expect(screen.getByRole('button', { name: /Retomar esta análise/ })).toBeDisabled();
  expect(network).not.toHaveBeenCalled();
  view.unmount(); render(<VisionLab endpoint="https://central.example" token="" onChange={async () => {}} />);
  expect(await screen.findByText('Mitose: divisão celular.')).toBeInTheDocument(); expect(network).not.toHaveBeenCalled();
});
